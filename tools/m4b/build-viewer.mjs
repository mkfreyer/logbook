import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
const result = await build({ entryPoints: ['src/features/model3d/web/viewer.ts'], bundle: true, write: false,
  format: 'iife', platform: 'browser', target: ['safari16'], minify: true, legalComments: 'inline' });
const license = await readFile('node_modules/three/LICENSE', 'utf8');
const code = `${result.outputFiles[0].text}\n/* Three.js license:\n${license}\n*/`;
const output = `// Generated by npm run viewer:build; edit web/viewer.ts instead.\nexport const viewerBundle = ${JSON.stringify(code)};\n`;
const target = 'src/features/model3d/generated/viewerBundle.ts';
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Viewer bundle is stale. Run npm run viewer:build.');
  console.log('Viewer bundle is current.');
} else { await writeFile(target, output); console.log(`Viewer bundle: ${Buffer.byteLength(code)} bytes, local and self-contained.`); }
